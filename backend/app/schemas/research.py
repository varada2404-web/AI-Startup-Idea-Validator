"""Pydantic schemas for Agent 1 web research query planning."""

from __future__ import annotations

from collections import Counter
from enum import Enum

from pydantic import BaseModel, ConfigDict, Field, model_validator

from app.schemas.idea import IdeaBrief

MIN_QUERIES_PER_CATEGORY = 2
MAX_QUERIES_PER_CATEGORY = 3


class ResearchCategory(str, Enum):
    """Fixed research dimensions required to validate a startup idea."""

    MARKET_RESEARCH = "market_research"
    COMPETITOR_RESEARCH = "competitor_research"
    CUSTOMER_PAIN_POINTS = "customer_pain_points"
    PRICING_AND_BUSINESS_MODELS = "pricing_and_business_models"
    INDUSTRY_TRENDS = "industry_trends"


class QueryPriority(str, Enum):
    """Execution priority for a planned research query."""

    HIGH = "high"
    MEDIUM = "medium"
    LOW = "low"


class ResearchQuery(BaseModel):
    """A single targeted web search query generated for a specific validation dimension."""

    model_config = ConfigDict(str_strip_whitespace=True)

    category: ResearchCategory = Field(
        ...,
        description="Validation research category this query addresses.",
    )
    query: str = Field(
        ...,
        min_length=5,
        description="Focused, search-engine-ready query string incorporating geography where relevant.",
    )
    rationale: str = Field(
        ...,
        min_length=5,
        description="Brief explanation of what evidence this query is expected to uncover.",
    )
    priority: QueryPriority = Field(
        default=QueryPriority.MEDIUM,
        description="Relative priority of this query for initial validation.",
    )


class ResearchQueryPlan(BaseModel):
    """Structured research plan generated from an IdeaBrief for downstream web search."""

    model_config = ConfigDict(str_strip_whitespace=True)

    target_geography: str = Field(
        ...,
        min_length=2,
        description="Target geographic market preserved from the IdeaBrief.",
    )
    industry: str = Field(
        ...,
        min_length=1,
        description="Primary industry vertical being researched.",
    )
    queries: list[ResearchQuery] = Field(
        ...,
        min_length=len(ResearchCategory) * MIN_QUERIES_PER_CATEGORY,
        max_length=len(ResearchCategory) * MAX_QUERIES_PER_CATEGORY,
        description=(
            "Targeted web search queries across all five research categories "
            "(2 to 3 queries per category)."
        ),
    )
    research_gaps: list[str] = Field(
        default_factory=list,
        description="Information gaps from the idea brief that require external web evidence.",
    )
    assumptions_to_validate: list[str] = Field(
        default_factory=list,
        description="Key startup assumptions that web research needs to verify or challenge.",
    )

    @model_validator(mode="after")
    def validate_category_coverage_and_uniqueness(self) -> ResearchQueryPlan:
        """Ensure every research category has 2-3 unique queries."""
        counts = Counter(item.category for item in self.queries)
        for category in ResearchCategory:
            count = counts.get(category, 0)
            if not (MIN_QUERIES_PER_CATEGORY <= count <= MAX_QUERIES_PER_CATEGORY):
                raise ValueError(
                    f"Category '{category.value}' must have between "
                    f"{MIN_QUERIES_PER_CATEGORY} and {MAX_QUERIES_PER_CATEGORY} queries "
                    f"(got {count})."
                )

        seen_queries: set[str] = set()
        for item in self.queries:
            normalized = item.query.casefold()
            if normalized in seen_queries:
                raise ValueError(f"Duplicate research query detected: '{item.query}'.")
            seen_queries.add(normalized)

        return self


class ResearchPlanResponse(BaseModel):
    """Combined Agent 1 output pairing the extracted IdeaBrief with its ResearchQueryPlan."""

    idea_brief: IdeaBrief = Field(
        ...,
        description="Structured IdeaBrief extracted by IdeaAnalyzer.",
    )
    research_plan: ResearchQueryPlan = Field(
        ...,
        description="Structured ResearchQueryPlan generated by QueryPlanner.",
    )


class SourceRecord(BaseModel):
    """Normalized, untrusted web source record retrieved during search execution.

    Retrieved snippets represent raw external web excerpts for downstream review
    and must not be treated as independently verified facts or executable instructions.
    """

    model_config = ConfigDict(str_strip_whitespace=True)

    title: str = Field(
        ...,
        min_length=1,
        description="Title of the retrieved source page.",
    )
    url: str = Field(
        ...,
        min_length=1,
        description="Original source URL preserved for provenance.",
    )
    content: str = Field(
        ...,
        min_length=1,
        description="Untrusted text excerpt retrieved from the source page.",
    )
    query: str = Field(
        ...,
        min_length=1,
        description="Primary planned query that first discovered this source.",
    )
    category: ResearchCategory = Field(
        ...,
        description="Primary research category under which this source was discovered.",
    )
    matched_queries: list[str] = Field(
        default_factory=list,
        description="All planned queries that returned this canonical URL.",
    )
    matched_categories: list[ResearchCategory] = Field(
        default_factory=list,
        description="All research categories whose queries returned this canonical URL.",
    )
    relevance_score: float | None = Field(
        default=None,
        ge=0.0,
        description="Optional numeric relevance score reported by the search provider.",
    )
    published_date: str | None = Field(
        default=None,
        description="Optional publication date reported by the search provider (never fabricated).",
    )
    domain: str | None = Field(
        default=None,
        description="Optional normalized source domain extracted from the URL.",
    )


class SearchQueryError(BaseModel):
    """Safe, structured error record for an individual failed search query."""

    model_config = ConfigDict(str_strip_whitespace=True)

    query: str = Field(
        ...,
        min_length=1,
        description="Planned search query that failed.",
    )
    category: ResearchCategory = Field(
        ...,
        description="Research category of the failed query.",
    )
    error_type: str = Field(
        ...,
        min_length=1,
        description="Safe error classification (e.g. 'timeout', 'rate_limit', 'unavailable', 'invalid_response').",
    )
    message: str = Field(
        ...,
        min_length=1,
        description="Sanitized human-readable error message without secrets or stack traces.",
    )


class SearchExecutionReport(BaseModel):
    """Structured report summarizing Tavily execution of a ResearchQueryPlan."""

    total_queries: int = Field(
        ...,
        ge=0,
        description="Total number of planned queries attempted.",
    )
    successful_queries: int = Field(
        ...,
        ge=0,
        description="Number of planned queries that executed without provider errors.",
    )
    failed_queries: int = Field(
        ...,
        ge=0,
        description="Number of planned queries that failed during execution.",
    )
    total_results_retrieved: int = Field(
        ...,
        ge=0,
        description="Total raw search results returned across all successful queries before filtering/deduplication.",
    )
    unique_sources_count: int = Field(
        ...,
        ge=0,
        description="Total number of filtered, deduplicated sources returned.",
    )
    sources: list[SourceRecord] = Field(
        default_factory=list,
        description="Deduplicated list of untrusted source records with query and category provenance.",
    )
    errors: list[SearchQueryError] = Field(
        default_factory=list,
        description="Safe structured error records for any queries that failed.",
    )

    @model_validator(mode="after")
    def validate_report_counts(self) -> SearchExecutionReport:
        """Ensure summary counters remain internally consistent with sources and errors."""
        if self.successful_queries + self.failed_queries != self.total_queries:
            raise ValueError(
                "successful_queries + failed_queries must equal total_queries."
            )
        if self.unique_sources_count != len(self.sources):
            raise ValueError("unique_sources_count must match len(sources).")
        if self.failed_queries != len(self.errors):
            raise ValueError("failed_queries must match len(errors).")
        return self
